/** Card photo for a room: admin-chosen photos first, then the room's own
 * seeded pool, then the type fallback. */
export function roomPhoto(room) {
  if (room && Array.isArray(room.photos) && room.photos.length) return room.photos[0];
  const pool = room && ROOM_PHOTOS_BY_NAME[room.name];
  if (pool && pool.length) return pool[0];
  return ROOM_PHOTOS[(room && room.type) || 'Standard'] || ROOM_PHOTOS.Standard;
}

/** Full gallery for a room's detail page: admin-chosen photos first, then the
 * per-room pool, then the type fallback. */
export function roomPhotos(room) {
  if (room && Array.isArray(room.photos) && room.photos.length) return room.photos;
  const pool = room && ROOM_PHOTOS_BY_NAME[room.name];
  if (pool && pool.length) return pool;
  const type = (room && room.type) || 'Standard';
  return [ROOM_PHOTOS[type] || ROOM_PHOTOS.Standard, HERO_IMAGE];
}

/** URL-safe slug for a room name — shared by the social-card generator, the
 * SPA and the prerender so filenames and og:image URLs always agree. */
export function roomSlug(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Branded social-card (og:image) path for a room's page. Only seeded rooms
 * have a generated card; admin-created rooms fall back to their photo (their
 * slug has no card on disk, so the branded URL would 404). */
export function roomCardImage(room) {
  if (room && ROOM_PHOTOS_BY_NAME[room.name]) return `/social/rooms/${roomSlug(room.name)}.png`;
  return roomPhoto(room);
}
