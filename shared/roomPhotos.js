export const HERO_IMAGE = '/images/hero.jpg';

// Responsive width variants generated by `npm run generate:images` into
// <dir>/resp/<base>-<w>.jpg for every self-hosted image (room pool, page
// banners, hero). Must match WIDTHS in scripts/generate-image-variants.mjs.
export const IMG_RESP_WIDTHS = [480, 800, 1200];

/** srcset string for a self-hosted photo, or null when no variants exist
 * (admin uploads and non-image / non-/images paths). Sizes are chosen per
 * component with a `sizes` attribute; omitting srcset keeps the plain `src`
 * fallback for anything outside the generated pool. `fmt` picks the codec:
 * 'jpg' (default) | 'webp' | 'avif' — the generator emits all three per width
 * and <picture> serves them in that order. */
export function imgSrcset(src, fmt = 'jpg') {
  if (typeof src !== 'string' || !src.startsWith('/images/') || src.startsWith('/images/uploads/')) return null;
  if (!/\.jpe?g$/i.test(src)) return null;
  const m = src.match(/^(.*\/)([^/]+)\.jpe?g$/i);
  if (!m) return null;
  const [, dir, base] = m;
  const ext = fmt === 'avif' ? 'avif' : fmt === 'webp' ? 'webp' : 'jpg';
  return IMG_RESP_WIDTHS.map((w) => `${dir}resp/${base}-${w}.${ext} ${w}w`).join(', ');
}

